/* Новогодняя копилка: товары по регионам.
   Для каждого товара заполните: title (название), text (одна строка, почему это хорошо),
   shop (магазин), url (партнёрская ссылка). Пока url пустой, товар показывается как «СКОРО».
   Регионы: us (США и Канада), uk (Великобритания и Ирландия), eu (Европа), cis (Россия и СНГ),
   oceania (Австралия и Новая Зеландия), other (другие страны). */
(function () {
  var slots = [
    ['Ежедневник', 'Для записей и маленьких шагов к разговору.'],
    ['Игрушка', 'Тёплый подарок для мамы или дочери.'],
    ['Украшение', 'Подарок, который говорит «я о тебе думаю».'],
    ['Календарь', 'Календарь на новый год с небольшими заданиями для двоих.']
  ];
  var regions = ['us', 'uk', 'eu', 'cis', 'oceania', 'other'];
  var c = {};
  regions.forEach(function (r) {
    c[r] = slots.map(function (s) {
      return { title: s[0], text: s[1], shop: '', url: '' };
    });
  });
  /* Пример заполнения:
     c.us[0] = { title: 'Название ежедневника', text: 'Почему подойдёт', shop: 'Amazon', url: 'https://...' };
  */
  window.COLLECTION = c;
})();
